#!/usr/bin/env bash
# Derive packages/portal/.env.local from PLATFORM_* vars in a source .env file.
#
# NEXT_PUBLIC_API_URL / NEXT_PUBLIC_SITE_NAME / NEXT_PUBLIC_SITE_TAGLINE are
# generated from PLATFORM_API_URL / PLATFORM_SITE_NAME / PLATFORM_SITE_TAGLINE,
# so the portal doesn't need its own hand-maintained copies of values the rest
# of the platform already configures. .env.local is Next.js's highest-
# precedence, always-gitignored override file (loaded in both `next dev` and
# `next build`), so this layers on top of packages/portal/.env.development /
# .env.production without touching either — it's regenerated on every run,
# never meant to be hand-edited.
#
# A var that isn't set in the source file is simply omitted here, so
# site-config.ts / lib/api.ts's own `|| "default"` fallback applies exactly as
# it does today.
#
# The source file is optional: if it doesn't exist, PLATFORM_* is still read
# from whatever's already in the environment (falls through to nothing set,
# so the output is empty and Next.js's own precedence takes over).
#
# This script only feeds .env.local, which is NOT used by the Docker build
# (packages/portal/.dockerignore excludes it, so it never reaches that build
# context) — that path instead bakes values in via `docker build --build-arg`,
# with packages/portal/.env.production as the committed fallback. This script
# covers the two host-run (non-Docker) paths below, where .env.local is what
# Next.js actually reads.
#
# Usage:
#   bin/generate-portal-env.sh <path-to-source-.env-file>
#
# Called from:
#   Makefile (dev-portal, dev-all-portal, install-portal, build-portal) and
#     bin/dev.sh (start_portal)        -> against the repo-root .env

set -euo pipefail

SRC_ENV="${1:?Usage: generate-portal-env.sh <path-to-.env-file>}"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$REPO_ROOT/packages/portal/.env.local"

if [ -f "$SRC_ENV" ]; then
  set -a
  # shellcheck disable=SC1090
  source "$SRC_ENV"
  set +a
fi

{
  echo "# Auto-generated by bin/generate-portal-env.sh from $SRC_ENV"
  echo "# Do not edit directly — regenerated on every dev/build run."
  [ -n "${PLATFORM_API_URL:-}" ] && echo "NEXT_PUBLIC_API_URL=$PLATFORM_API_URL"
  [ -n "${PLATFORM_SITE_NAME:-}" ] && echo "NEXT_PUBLIC_SITE_NAME=$PLATFORM_SITE_NAME"
  [ -n "${PLATFORM_SITE_TAGLINE:-}" ] && echo "NEXT_PUBLIC_SITE_TAGLINE=$PLATFORM_SITE_TAGLINE"
  true
} > "$OUT"

exit 0
